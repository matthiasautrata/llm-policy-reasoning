"""slice.edn (+ extension.edn) -> LinkML instance YAML (slice.instance.yaml), for linkml-validate and gen-doc.

Field names map to snake_case slots; rule heads/bodies and claim assertions are re-serialised to EDN strings
(LinkML holds the envelope, EDN the rule language). Run: .venv/bin/python spikes/v3/v3a-prolog/linkml/edn2yaml.py
"""
import datetime, pathlib, sys
import edn_format as E, yaml

HERE = pathlib.Path(__file__).resolve().parent
SHARED = HERE.parents[1] / "shared"
RENAME = {"code-lists": "code_lists", "derived-by": "derived_by", "superior-to": "superior_to", "class": "rule_class",
          "code-list": "code_list", "type": "column_type"}
EDN_FIELDS = {"head", "body", "assertion"}


def name(k):
    return k.name if isinstance(k, E.Keyword) else str(k)


def iso(x):
    return x.isoformat()[:10] if isinstance(x, (datetime.date, datetime.datetime)) else x


def plain(x, ctx=None):
    if isinstance(x, E.Keyword): return x.name
    if isinstance(x, (datetime.date, datetime.datetime)): return iso(x)
    if hasattr(x, "items"):
        out = {}
        for k, v in x.items():
            k = name(k)
            if k in EDN_FIELDS:
                out[k] = E.dumps(v)
            elif v is not None:
                out[RENAME.get(k, k)] = plain(v, k)
        return out
    if isinstance(x, (list, tuple)) or type(x).__name__ == "ImmutableList": return [plain(v, ctx) for v in x]
    return x


def convert():
    S = E.loads((SHARED / "slice.edn").read_text())
    X = E.loads((SHARED / "extension.edn").read_text())
    out = plain(S)
    out["version"] = out.pop("slice/version")
    for c in out["concepts"]:
        c["concept_name"] = c.pop("name")
        if "columns" in c: c["columns_out"] = c.pop("columns")
    for t in out["taxonomies"]:
        t["groups"] = [{"group": g, "members": m} for g, m in t.pop("tree").items()]
    out["functional"] = [{"pred": p, "key_arity": n} for p, n in out["functional"].items()]
    for x in X:
        (out["rules"] if "kind" in plain(x) else out["claims"]).append(plain(x))
    return out


if __name__ == "__main__":
    doc = convert()
    p = HERE / "slice.instance.yaml"
    p.write_text("# generated by edn2yaml.py from shared/slice.edn + shared/extension.edn; do not edit\n"
                 + yaml.safe_dump(doc, sort_keys=False, allow_unicode=True, width=120))
    print(p, sum(1 for _ in p.open()), "lines")
